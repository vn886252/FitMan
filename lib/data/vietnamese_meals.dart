/// Dữ liệu thực đơn món ăn Việt Nam chuẩn dinh dưỡng cho thể hình (90 món phong phú)
class VietnameseMealOption {
  final String id;
  final String name;
  final String portion;
  final int calories;
  final double protein;
  final double carbs;
  final double fat;
  final String icon;
  final String category; // 'breakfast', 'lunch', 'dinner', 'snack', 'pre_workout', 'post_workout'
  final String? note;

  const VietnameseMealOption({
    required this.id,
    required this.name,
    required this.portion,
    required this.calories,
    required this.protein,
    required this.carbs,
    required this.fat,
    required this.icon,
    required this.category,
    this.note,
  });

  VietnameseMealOption scale(double factor) => VietnameseMealOption(
    id: id,
    name: name,
    portion: factor == 1.0 ? portion : '$portion (x${factor == factor.roundToDouble() ? factor.toInt() : factor})',
    calories: (calories * factor).round(),
    protein: double.parse((protein * factor).toStringAsFixed(1)),
    carbs: double.parse((carbs * factor).toStringAsFixed(1)),
    fat: double.parse((fat * factor).toStringAsFixed(1)),
    icon: icon,
    category: category,
    note: note,
  );

  Map<String, dynamic> toJson() => {
    'id': id,
    'name': name,
    'portion': portion,
    'calories': calories,
    'protein': protein,
    'carbs': carbs,
    'fat': fat,
    'icon': icon,
    'category': category,
    if (note != null) 'note': note,
  };

  factory VietnameseMealOption.fromJson(Map<String, dynamic> json) => VietnameseMealOption(
    id: json['id'] as String,
    name: json['name'] as String,
    portion: json['portion'] as String,
    calories: (json['calories'] as num).toInt(),
    protein: (json['protein'] as num).toDouble(),
    carbs: (json['carbs'] as num).toDouble(),
    fat: (json['fat'] as num).toDouble(),
    icon: json['icon'] as String,
    category: json['category'] as String,
    note: json['note'] as String?,
  );
}

